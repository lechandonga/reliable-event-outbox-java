CREATE TABLE IF NOT EXISTS business_orders (
    id VARCHAR(64) PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS outbox_events (
    id VARCHAR(64) PRIMARY KEY,
    aggregate_key VARCHAR(128) NOT NULL,
    sequence_no BIGINT NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    payload CLOB NOT NULL,
    status VARCHAR(32) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL,
    next_attempt_at TIMESTAMP NOT NULL,
    locked_at TIMESTAMP,
    locked_by VARCHAR(128),
    sent_at TIMESTAMP,
    succeeded_at TIMESTAMP,
    dead_at TIMESTAMP,
    last_error CLOB,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_outbox_aggregate_sequence UNIQUE (aggregate_key, sequence_no)
);

CREATE INDEX IF NOT EXISTS idx_outbox_due
    ON outbox_events (next_attempt_at, status);

CREATE TABLE IF NOT EXISTS event_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(64) NOT NULL,
    aggregate_key VARCHAR(128) NOT NULL,
    sequence_no BIGINT NOT NULL,
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    attempts INTEGER NOT NULL,
    reason CLOB,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_event_history_event
    ON event_status_history (event_id, id);

CREATE TABLE IF NOT EXISTS consumed_events (
    event_id VARCHAR(64) PRIMARY KEY,
    aggregate_key VARCHAR(128) NOT NULL,
    sequence_no BIGINT NOT NULL,
    consumed_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS aggregate_progress (
    aggregate_key VARCHAR(128) PRIMARY KEY,
    last_sequence_no BIGINT NOT NULL,
    last_event_id VARCHAR(64) NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS order_projection (
    aggregate_key VARCHAR(128) PRIMARY KEY,
    order_id VARCHAR(64) NOT NULL,
    title VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    applied_event_count INTEGER NOT NULL,
    updated_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS aggregate_sequence (
    aggregate_key VARCHAR(128) PRIMARY KEY,
    last_sequence_no BIGINT NOT NULL
);
